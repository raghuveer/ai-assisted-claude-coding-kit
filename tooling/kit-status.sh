# A rule the indexer refused is the OTHER reason a floor can be missing, and without this the
# message above claims the benign one — "nothing to go on" — about a task that declared its
# paths and had them judged by a rule that was thrown away. The indexer says this on stderr
# too, but kit-status.sh runs it with stderr discarded, so the terminal warning reaches nobody
# and the file is what gets read.
# A path git would only give us quoted -- one containing a double quote, a backslash or a
# control byte -- is dropped rather than recorded under a name that matches no rule. That is
# the same "missing floor" the message above describes, arriving by a different route, and it
# has to be said for the same reason: the benign cause must not stand in for this one.
UNUSABLE=$(q "SELECT value FROM meta WHERE key='paths_unusable';")
case "${UNUSABLE:-0}" in ''|0) ;; *)
  printf '\n> **%s changed path(s) could not be indexed.** git only reports a name containing a\n' "$UNUSABLE"
  printf '> quote, a backslash or a control byte in escaped form, and a floor derived from that\n'
  printf '> name would match nothing — so those files carry no `touches` edge and no floor here.\n'
  printf '> Blast radius and tier floor are therefore incomplete for them, not clean.\n' ;;
esac

REFUSED=$(q "SELECT value FROM meta WHERE key='tier_rules_refused';")
case "${REFUSED:-0}" in ''|0) ;; *)
  printf '\n> **%s `tier.rule` line(s) refused as unusable, so their floor never applied:**\n' "$REFUSED"
  printf '> `%s`\n' "$(q "SELECT value FROM meta WHERE key='tier_rules_refused_text';")"
  printf '> A refused rule is not an absent one — any "unverified" above may be this, not a\n'
  printf '> task with nothing to go on. Fix the glob in `.claude/project-profile.md`.\n' ;;
esac

# ---- the plan (ADR 0004) -----------------------------------------------------------------
# Two conditions, and they are different failures said differently. A STALE plan loaded fine
# and describes a backlog that has moved. An ORPHANED pack directory has no plan at all behind
# it and is the shape the whole ADR is about: before the plan was persisted, every kit-index.sh
# run left exactly this -- pack files on disk, looking current, that skills/task-context would
# never load because its step 4 finds no row.
# A REFUSED plan is reported first and by name. It used to be reported as an orphaned pack —
# zero rows loaded looks identical to no plan written — which is the wrong cause and the wrong
# remedy, and after a merge it is the EXPECTED state, because .gitattributes deliberately
# declines merge=union so two plans conflict rather than interleave.
# The cluster-size distribution. It was absent, so a 70-of-85 cluster could only be found by
# querying plan_item by hand — which is how it went unnoticed while the packs built from it were
# being proposed as the subject of an ROI experiment.
q "SELECT substr(key,21)||' '||value FROM meta WHERE key LIKE 'cluster_largest_pct:%';" | tr -d '\r' |
while IFS=' ' read -r _g _pct; do
  [ -n "$_g" ] || continue
  printf '\n> **Largest cluster in `%s` holds %s%% of its planned tasks.**' "$_g" "$_pct"
  if [ "${_pct:-0}" -gt 60 ]; then
    printf ' Packs are **withheld** —\n'
    printf '> a pack built from a cluster that size names most of the repository, which is worse\n'
    printf '> than no pack. The ordering is unaffected: layers come from topology and ranks from\n'
    printf '> score. Raise `cluster.max_share` to accept it, or fix the grouping.\n'
  else
    printf '\n'
  fi
done

# A gitignored plan is the quietest way to undo this whole mechanism: everything works on the
# machine that planned, and the guarantee ADR 0004 publishes is false everywhere else.
q "SELECT substr(key,14) FROM meta WHERE key LIKE 'plan_ignored:%';" | tr -d '\r' |
while IFS= read -r _g; do
  [ -n "$_g" ] || continue
  printf '\n> **The plan for `%s` is covered by `.gitignore`.** It will not survive a clone, a\n' "$_g"
  printf '> new machine, or a deleted index — which is the machine-local state ADR 0004 exists to\n'
  printf '> abolish, arriving through configuration rather than code. Everything looks correct\n'
  printf '> here and is absent for everyone else. Un-ignore `.project/plans/`.\n'
done

PLANREF=$(q "SELECT value FROM meta WHERE key='plan_refused';")
case "${PLANREF:-0}" in ''|0) ;; *)
  printf '\n> **%s plan file(s) were parsed and REFUSED, so their ordering is not loaded:**\n' "$PLANREF"
  printf '> `%s`\n' "$(q "SELECT value FROM meta WHERE key='plan_refused_text';")"
  printf '> A refused plan is not an absent one. Conflict markers from a merge are the usual\n'
  printf '> cause — the plan is deliberately not `merge=union`, so two orderings conflict\n'
  printf '> rather than silently interleaving. Resolve the file, or re-run `kit-plan.sh`.\n' ;;
esac

# `while IFS= read -r`, not `for _g in $(...)`. A goal id reaches this loop from a committed
# plan file, and an unquoted command substitution word-splits and globs it: a goal named `*`
# expanded local filenames into this report. kit-index.sh names that exact shape as the one
# LESSONS §4 says to sweep for, and SECURITY.md §5 forbids it.
q "SELECT substr(key,12) FROM meta WHERE key LIKE 'plan_stale:%';" | tr -d '\r' |
while IFS= read -r _g; do
  [ -n "$_g" ] || continue
  printf '\n> **The plan for `%s` was computed from a different backlog.** Tasks have been\n' "$_g"
  printf '> added, closed, re-tiered or re-blocked since it was written, so its ordering may name\n'
  printf '> work that no longer exists and omit work that does. It is still loaded and still\n'
  printf '> readable — this is a notice, not a withdrawal. Re-run `kit-plan.sh` to refresh it.\n'
done

# The INVERSE of the orphan check below, and the one a fresh clone actually hits: the plan is
# committed and the packs are gitignored, so a clone arrives with rows and no pack — and
# skills/task-context step 4 builds a path from the row and reads nothing. Silent before; the
# skill has no miss branch, so the agent simply got less context than it was told it had.
MISSINGPACKS=""
q "SELECT DISTINCT goal_id FROM plan_item;" | tr -d '\r' |
while IFS= read -r _g; do
  [ -n "$_g" ] || continue
  # A goal whose packs were WITHHELD is not a goal whose packs are missing. The notice above
  # already names the cause; repeating it here as "run kit-plan.sh --packs" would send the
  # reader to a remedy that refuses for the same reason — wrong cause, wrong remedy, which is
  # the defect a T3 security review flagged when a refused plan was reported as an orphan.
  [ "$(q "SELECT COUNT(*) FROM meta WHERE key='cluster_packs_withheld:$(printf '%s' "$_g" | sed "s/'/''/g")';")" = 0 ] || continue
  [ -d "$ROOT/$STATE_DIR/packs/$_g" ] || printf '%s\n' "$_g"
done > "$OUT.missingpacks" 2>/dev/null
if [ -s "$OUT.missingpacks" ]; then
  printf '\n> **Plan row(s) with no cluster pack on disk:** %s\n' "$(tr '\n' ' ' < "$OUT.missingpacks")"
  printf '> A fresh clone looks exactly like this — the plan is committed and the packs are not.\n'
  printf '> `skills/task-context` step 4 will build a pack path from the plan row and find\n'
  printf '> nothing there. Rebuild them from the plan you already have, which does NOT recompute\n'
  printf '> the ordering:  `bash tooling/kit-plan.sh --packs`\n'
fi
rm -f "$OUT.missingpacks"

if [ -d "$ROOT/$STATE_DIR/packs" ]; then
  ORPHANED=""
  for _pd in "$ROOT/$STATE_DIR/packs"/*; do
    [ -d "$_pd" ] || continue
    _pg=${_pd##*/}
    _n=$(q "SELECT COUNT(*) FROM plan_item WHERE goal_id='$(printf '%s' "$_pg" | sed "s/'/''/g")';")
    case "${_n:-0}" in 0) ORPHANED="$ORPHANED $_pg" ;; esac
  done
  # Suppressed when a plan was refused: those packs have a plan, it just did not load, and the
  # notice above already names the real cause. Reporting "re-run kit-plan.sh, or delete them"
  # over a conflicted file sends the reader to the wrong remedy.
  if [ -n "$ORPHANED" ] && [ "${PLANREF:-0}" = 0 ]; then
    printf '\n> **Cluster pack(s) on disk with no plan behind them:**%s\n' "$ORPHANED"
    printf '> A pack is a cache of a plan. With no `plan_item` row, `skills/task-context` step 4\n'
    printf '> finds nothing and never reads them — so these are resident cost returning nothing,\n'
    printf '> not context anybody is being served. Re-run `kit-plan.sh`, or delete them.\n'
  fi
fi

if [ "$REQUIRED" -gt 0 ] && [ $(( UNTAG * 100 / REQUIRED )) -gt 20 ]; then
  printf '\n> **Trailer discipline degraded.** %s of %s non-trivial commits carry no `Task-Id`' "$UNTAG" "$REQUIRED"
  [ "$EXEMPTN" -gt 0 ] && printf ' (%s trivial commit(s) excluded per `git.trivial_pattern`)' "$EXEMPTN"
  printf '.\n'
  printf '> Derived status under-reports; an empty backlog here may be a measurement failure, not an idle repo.\n'
fi
} > "$OUT"
echo "${OUT#$ROOT/}"
